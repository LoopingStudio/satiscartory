// Scans public/assets/kenney/<kit>/*.glb and writes a typed manifest.
// Run: npm run manifest
import { readdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const kenneyDir = join(root, 'public/assets/kenney');
const out = join(root, 'src/core/assets/manifest.gen.ts');

const kits = readdirSync(kenneyDir, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .sort();

const entries = [];
for (const kit of kits) {
  const files = readdirSync(join(kenneyDir, kit))
    .filter((f) => f.endsWith('.glb'))
    .sort();
  for (const f of files) {
    entries.push([`${kit}/${f.replace(/\.glb$/, '')}`, `assets/kenney/${kit}/${f}`, kit]);
  }
}

const lines = [
  '// AUTO-GENERATED by scripts/gen-manifest.mjs — do not edit.',
  '',
  `export const KITS = ${JSON.stringify(kits)} as const;`,
  'export type KitName = (typeof KITS)[number];',
  '',
  'export const MODELS = {',
  ...entries.map(([key, path]) => `  ${JSON.stringify(key)}: ${JSON.stringify(path)},`),
  '} as const;',
  '',
  'export type ModelKey = keyof typeof MODELS;',
  '',
  'export function kitOf(key: ModelKey): KitName {',
  "  return key.slice(0, key.indexOf('/')) as KitName;",
  '}',
  '',
];
writeFileSync(out, lines.join('\n'));
console.log(`manifest: ${entries.length} models in ${kits.length} kits -> ${out}`);
